const { JSDOM } = require("jsdom"); const fs = require("fs"), path = require("path");
const dir = require("path").join(__dirname, "..") + "/";
let pass = 0, fail = 0; const check = (n, c) => { (c ? pass++ : fail++); console.log(c ? "PASS" : "FAIL", n); };
const raw = fs.readFileSync(dir + "progress.html", "utf8");
const html = raw.replace(/<script src="https?:[^>]*><\/script>/g, "").replace(/<link [^>]*>/g, "").replace(/<script src="[^"]+"[^>]*><\/script>/g, "");
const dom = new JSDOM(html, { runScripts: "outside-only", pretendToBeVisual: true, url: "http://localhost/" });
const w = dom.window; w.confirm = () => true; w.URL.createObjectURL = () => "blob:x";
// seed local progress before the page runs
w.localStorage.setItem("cmdcraft_completed", JSON.stringify(["LNX-NAV-01", "LNX-NAV-02", "LNX-NAV-03"]));
w.localStorage.setItem("cmdcraft_xp", "150");
w.localStorage.setItem("cmdcraft_stats", JSON.stringify({ "LNX-NAV-01": { n: 2, f: 1, b: 0, d: Date.now() - 1000, t: 0 } }));
w.localStorage.setItem("cmdcraft.sql.v1", JSON.stringify({ solved: { "SEL-01": 1, "SEL-02": 2 }, attempts: {}, xp: 40 }));
w.eval([...raw.matchAll(/<script src="([^"h][^"]*)"/g)].map(m => m[1]).filter(x => !/theme/.test(x)).map(x => fs.readFileSync(dir + x, "utf8")).join("\n;\n"));
w.eval(html.match(/<script>([\s\S]*?)<\/script>/g).map(s => s.replace(/<\/?script>/g, "")).join("\n"));
const $ = id => w.document.getElementById(id);
const txt = $("cards").textContent;
check("five subject cards", $("cards").children.length === 5);
check("Linux practice shows solved vs total with XP", /3 \//.test(txt) && /150 XP/.test(txt));
check("review-due note links to review mode", /1 drill due for review/.test(txt) && $("cards").querySelector("a[href='linux/?review=1']"));
check("SQL progress counts solved problems", /2 \/ 4\d\d/.test(txt) && /40 XP/.test(txt));
check("theory card counts commands", /242 \/ 242/.test(txt));
let blob = null; w.Blob = function (parts) { blob = parts.join(""); this.parts = parts; };
$("btn-export").click();
const exported = JSON.parse(blob);
check("export contains app marker and cmdcraft keys only", exported.app === "cmdcraft" && exported.data.cmdcraft_xp === "150" && Object.keys(exported.data).every(k => /^cmdcraft/i.test(k)));
w.localStorage.clear();
const reloaded = { n: 0 }; 
const file = { files: [{ name: "x.json" }] };
w.FileReader = function () { this.readAsText = () => { this.result = JSON.stringify(exported); this.onload(); }; };
Object.defineProperty($("file"), "files", { value: [{}] });
w.location.reload = () => { reloaded.n++; };
$("file").dispatchEvent(new w.Event("change"));
check("import restores progress", w.localStorage.getItem("cmdcraft_xp") === "150" && !!w.localStorage.getItem("cmdcraft.sql.v1"));
w.FileReader = function () { this.readAsText = () => { this.result = '{"hello":1}'; this.onload(); }; };
$("file").dispatchEvent(new w.Event("change"));
check("import rejects a file that is not a CmdCraft export", /Import failed/.test($("io-msg").textContent));
console.log(pass + " passed, " + fail + " failed"); process.exit(fail ? 1 : 0);
